"""Opt-in full tutorial regression against the original Python/C++ dynamics."""
import importlib.util
import os
from pathlib import Path
import numpy as np
import pytest
from libra_py.dyn.methods.qtag._backend import to_numpy


@pytest.mark.skipif(os.environ.get('QTAG_FULL_TESTS') != '1',
                    reason='set QTAG_FULL_TESTS=1 for the full 800-step tutorial')
@pytest.mark.parametrize('backend', ['numpy', 'torch'])
def test_holstein_density_snapshots(backend, tmp_path, monkeypatch):
    """Check actual plotted times and all 100 density points on both surfaces.

    The fixture comes from legacy compute.run_qtag using the source notebook's
    parameters and C++ solver; it is not generated by the new array workflow.
    This catches changed fit tolerances as well as an off-by-one snapshot index.
    """
    if backend == 'torch':
        pytest.importorskip('torch')
    example = Path(__file__).resolve().parents[5]/'examples/libra_py/dyn/methods/qtag/1_basics'
    monkeypatch.syspath_prepend(str(example))
    spec = importlib.util.spec_from_file_location('qtag_basics', example/'run.py')
    tutorial = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tutorial)
    waves = []
    monkeypatch.setattr(tutorial.plot, 'wf_plot', lambda wave, *args: waves.append(wave))
    tutorial.main(backend=backend, output=tmp_path)
    with np.load(Path(__file__).parent/'data/holstein_reference.npz') as reference:
        np.testing.assert_array_equal(waves[0]['snaps'], reference['steps'])
        np.testing.assert_allclose(to_numpy(waves[0]['times']), .01*reference['steps'])
        np.testing.assert_allclose(to_numpy(waves[0]['density']), reference['density'],
                                   rtol=2e-5, atol=2e-6)
